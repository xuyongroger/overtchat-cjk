/** A replacement rule for text that embeds a variable, e.g. "5 messages". */
export interface ZhPattern {
  /** Must be anchored and match English only, so the Chinese output cannot re-match. */
  pattern: RegExp;
  /** String (supports `$1`) or a builder over the regexp match. */
  replace: string | ((match: RegExpExecArray) => string);
}

